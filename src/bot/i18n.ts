const DICTS: Record<Lang, Dict> = { ru: RU, en: EN, uz: UZ };

export function normalizeLang(l: string | null | undefined): Lang {
  return l === "en" || l === "uz" ? l : "ru";
}

export function t(lang: string | null | undefined, key: string, vars?: Record<string, string | number>): string {
  const L = normalizeLang(lang);
  let s = DICTS[L][key] ?? RU[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

